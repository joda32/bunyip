#!/usr/bin/env python3
"""Generate data/http_tech.json from a webappanalyzer checkout.

webappanalyzer (https://github.com/enthec/webappanalyzer) is GPL-3.0; the
generated file is a derived mapping of its per-technology `cpe` fields to
NVD vendor:product, used by `vulndb ingest`. Keep the provenance note in the
output file.

Usage:
    python3 scripts/gen_http_tech.py /path/to/webappanalyzer/src/technologies > data/http_tech.json
"""
import glob
import json
import re
import sys

APP_CPE = re.compile(r"^cpe:2\.3:a:([^:]+):([^:]+):")


def main(tech_dir: str) -> None:
    techs = {}
    for f in glob.glob(f"{tech_dir}/*.json"):
        with open(f, encoding="utf-8") as fh:
            techs.update(json.load(fh))
    rows, seen = [], set()
    for name in sorted(techs):
        cpe = techs[name].get("cpe")
        if not cpe:
            continue
        m = APP_CPE.match(cpe)
        if not m:
            continue
        key = (name.lower(), m.group(1), m.group(2))
        if key in seen:
            continue
        seen.add(key)
        rows.append({"name": name, "vendor": m.group(1), "product": m.group(2)})
    doc = {
        "comment": "Web technology NAME -> NVD CPE vendor:product, for `vulndb ingest`. Generated by "
                   "scripts/gen_http_tech.py from the webappanalyzer corpus "
                   "(https://github.com/enthec/webappanalyzer, GPL-3.0); a derived mapping of its 'cpe' fields.",
        "source": "generated:webappanalyzer",
        "tech": rows,
    }
    json.dump(doc, sys.stdout, indent=1, ensure_ascii=False)
    sys.stdout.write("\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
